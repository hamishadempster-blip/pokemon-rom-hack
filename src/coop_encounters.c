// Encounter variety (collection update §2): wild visitors.
//
// Some Pokémon visit a map only at a time of day (MORNING, DAY, EVENING,
// NIGHT, as GetTimeOfDay reports it, so waiting at a Pokémon Center and the
// linked shared clock count) or in a weather (rain, sandstorm, volcanic ash:
// the map's weather now). While a visitor's condition holds, 1 in 4
// encounters in its area (grass or cave, surfing, a rod, Rock Smash) is that
// visitor instead of the table's species, at the level of the table's own
// slot, so levels, Repel and Keen Eye work as before. Nothing is taken out of
// any table: every Pokémon found there before is still found.
//
// The data is src/data/coop_visitors.json, made into src/data/coop_visitors.h
// by tools/coop_encounters/visitors_to_header.py (which refuses a visitor
// already in that table, a map without that table, and other mistakes) and
// read by the acquisition manifest (tools/coop_roster_audit/roster.py), so the
// Pokédex hints and the manifest know every visitor.
//
// In co-op a wild battle is generated by the game that met it and sent to
// the partner, so a visitor is the same Pokémon on both screens.
//
// The WILDLIFE REPORT (CO-OP > WAIT HERE > REPORT, in a Pokémon Center) lists
// the visitors of the maps near that town, by condition: the names of those
// this save has seen, and a hint for the others.
