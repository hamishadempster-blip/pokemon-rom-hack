// Waiting at a Pokémon Center for another time of day (collection update §8).
//
// CO-OP > WAIT HERE, on any Pokémon Center's ground floor: rest until
// MORNING, DAY, EVENING or NIGHT (always forward, to 08:00, 10:00, 19:20 or
// 21:00), or back to the clock's own time (REAL TIME, once rested).
//
// The game's clock is never changed. A rest is a personal shift of the time
// of day only (CoopSaveV5.periodShift, minutes, 0-1439), added where the
// game works out the time of day (UpdateTimeOfDay in src/overworld.c). So
// the outdoor tint, night music, time-of-day encounters, evolutions and
// moves such as MOONLIGHT follow the rest. Days, berries, daily events,
// tides and every timer kept by the real clock do not move, so resting into
// "tomorrow" repeats nothing that happens once a day.
//
// Linked, both games already show the link master's time of day (the
// shared clock in src/coop_deal.c, which sends the master's rests too), so
// a rest is made together. The partner must be in the same Center and say
// YES: a deal of kind COOP_DEAL_WAIT, request and answer only; nothing is
// exchanged or saved. Each game then shifts its own time so that both reach
// the chosen period at the same moment and stay together after UNLINK. A
// linked player whose partner is elsewhere is told to meet first. A co-op
// wild encounter is always generated by one game and sent to the other, so
// the two never see different Pokémon for one encounter.
#include "global.h"
#include "coop.h"
#include "coop_deal.h"
#include "coop_time.h"
#include "event_data.h"
#include "overworld.h"
#include "rtc.h"
#include "string_util.h"
#include "constants/coop.h"
#include "constants/layouts.h"
#include "constants/rtc.h"

#define MINUTES_PER_DAY (24 * 60)

static const u8 sText_Morning[] = _("MORNING");
static const u8 sText_Day[] = _("DAY");
static const u8 sText_Evening[] = _("EVENING");
static const u8 sText_Night[] = _("NIGHT");
static const u8 sText_RealTime[] = _("your clock's own time");

static const u8 *const sPeriodNames[] = {
    [TIME_MORNING] = sText_Morning,
    [TIME_DAY] = sText_Day,
    [TIME_EVENING] = sText_Evening,
    [TIME_NIGHT] = sText_Night,
    [COOP_WAIT_REAL_TIME] = sText_RealTime,
};

// Where a rest ends, in minutes after midnight: inside each period
// (include/constants/rtc.h), where the outdoor tint (UpdateTimeOfDay)
// already looks like it. At a period's first minute the tint is still
// the previous period's: 06:00 looks like night.
static const u16 sPeriodLandMinute[TIMES_OF_DAY_COUNT] = {
    [TIME_MORNING] = (MORNING_HOUR_BEGIN + (MORNING_HOUR_END - MORNING_HOUR_BEGIN) / 2) * 60, // 08:00, full morning tint
    [TIME_DAY] = DAY_HOUR_BEGIN * 60,                   // 10:00
    [TIME_EVENING] = EVENING_HOUR_BEGIN * 60 + 20,      // 19:20 (evening lasts an hour)
    [TIME_NIGHT] = (NIGHT_HOUR_BEGIN + 1) * 60,         // 21:00, full night tint
};
STATIC_ASSERT(MORNING_HOUR_BEGIN == 6 && DAY_HOUR_BEGIN == 10 && EVENING_HOUR_BEGIN == 19 && NIGHT_HOUR_BEGIN == 20, CoopTimePeriodsAsDocumented);

u16 CoopTime_Shift(void)
{
    struct CoopSave *save = Coop_GetSave();

    if (save == NULL || save->v5.size != sizeof(struct CoopSaveV5)
     || save->v5.periodShift >= MINUTES_PER_DAY)
        return 0;
    return save->v5.periodShift;
}

// This game's own time of day, waits included (not the link master's).
void CoopTime_AdjustClock(s32 *hours, s32 *minutes)
{
    u32 shift = CoopTime_Shift();
    u32 total;

    if (shift == 0 || *hours < 0 || *hours >= 24 || *minutes < 0 || *minutes >= 60)
        return;
    total = (*hours * 60 + *minutes + shift) % MINUTES_PER_DAY;
    *hours = total / 60;
    *minutes = total % 60;
}

bool8 CoopTime_InCentre(void)
{
    switch (gMapHeader.mapLayoutId)
    {
    case LAYOUT_POKEMON_CENTER_1F:
    case LAYOUT_LAVARIDGE_TOWN_POKEMON_CENTER_1F:
    case LAYOUT_POKEMON_CENTER_1F_FRLG:
    case LAYOUT_RS_POKEMON_CENTER_1F:
    case LAYOUT_INDIGO_PLATEAU_POKEMON_CENTER_1F:
    case LAYOUT_ONE_ISLAND_POKEMON_CENTER_1F:
        return TRUE;
    }
    return FALSE;
}

bool8 CoopTime_TargetValid(u8 target)
{
    return target < TIMES_OF_DAY_COUNT || target == COOP_WAIT_REAL_TIME;
}

void CoopTime_BufferTarget(u8 target, u8 *dest)
{
    StringCopy(dest, CoopTime_TargetValid(target) ? sPeriodNames[target] : sText_RealTime);
}

// Special. VAR_RESULT: TRUE inside a Pokémon Center's ground floor (the CO-OP
// menu then offers WAIT HERE).
u16 CoopTime_CanWaitHere(void)
{
    return CoopTime_InCentre();
}

// Special. STR_VAR_1: the time of day shown now. VAR_RESULT: TRUE when this
// save has waited (REAL TIME is offered).
u16 CoopTime_BufferNow(void)
{
    enum TimeOfDay now = GetTimeOfDay();

    StringCopy(gStringVar1, sPeriodNames[now < TIMES_OF_DAY_COUNT ? now : TIME_DAY]);
    return CoopTime_Shift() != 0;
}

enum
{
    WAIT_PREP_SOLO,         // wait now
    WAIT_PREP_TOGETHER,     // linked, partner here: ask them
    WAIT_PREP_MEET_FIRST,   // linked, partner elsewhere
    WAIT_PREP_ALREADY,      // already that time of day
    WAIT_PREP_INVALID,
};

// Special. VAR_0x8006: the choice (TIME_* or COOP_WAIT_REAL_TIME).
// STR_VAR_2: its name. VAR_RESULT: WAIT_PREP_*.
u16 CoopTime_PrepareWait(void)
{
    u8 target = gSpecialVar_0x8006;

    if (!CoopTime_TargetValid(target) || !CoopTime_InCentre())
        return WAIT_PREP_INVALID;
    CoopTime_BufferTarget(target, gStringVar2);
    if (target == COOP_WAIT_REAL_TIME ? CoopTime_Shift() == 0 : GetTimeOfDay() == target)
        return WAIT_PREP_ALREADY;
    if (Coop_SessionActive())
        return Coop_DealPartnerHere() ? WAIT_PREP_TOGETHER : WAIT_PREP_MEET_FIRST;
    return WAIT_PREP_SOLO;
}

// Special, with the screen faded out. VAR_0x8006: the choice. Shifts this
// game's time of day forward to that period's landing time (or clears the
// shift). STR_VAR_2: its name.
void CoopTime_ApplyWait(void)
{
    struct CoopSave *save = Coop_GetSave();
    u8 target = gSpecialVar_0x8006;
    s32 hours, minutes;
    u32 now, start;

    if (!CoopTime_TargetValid(target))
        return;
    CoopTime_BufferTarget(target, gStringVar2);
    if (save == NULL || save->v5.size != sizeof(struct CoopSaveV5) || !Coop_SaveSchemaSupported())
        return;
    if (target == COOP_WAIT_REAL_TIME)
    {
        save->v5.periodShift = 0;
    }
    else
    {
        RtcCalcLocalTime();
        hours = gLocalTime.hours;
        minutes = gLocalTime.minutes;
        CoopTime_AdjustClock(&hours, &minutes);
        now = hours * 60 + minutes;
        start = sPeriodLandMinute[target];
        save->v5.periodShift = (CoopTime_Shift() + (start + MINUTES_PER_DAY - now)) % MINUTES_PER_DAY;
    }
    gTimeUpdateCounter = 0;     // re-tint and re-check forms on the next field frame
    UpdateTimeOfDay(FALSE);
}
