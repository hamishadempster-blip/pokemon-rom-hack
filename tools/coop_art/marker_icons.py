#!/usr/bin/env python3
"""Partner marker icons and edge arrows (16x16, 4bpp) for src/coop_outfit.c.

    tools/coop_art/marker_icons.py > src/data/coop_marker_icons.h

Each icon is drawn as a fill mask ('F' the player's colour, 'W' white, 'H'
the player's light shade); the dark outline (colour 15) is added around every
drawn pixel, so each icon reads on grass, water, buildings and cave floors.
Colours: 12 white, 13 highlight, 14 fill, 15 outline (the marker palette).
Icons sit at the bottom of the 16x16 square, centred, so they rest just
above the partner's head; arrows are centred.
"""
import math

ICONS = {
    # Walking: a small dot in the player's colour.
    'WALK': """
.HHF.
HFFFF
FFFFF
FFFFF
.FFF.
""",
    # Talking: a speech bubble.
    'TALK': """
FFFFFFFFF
FWFFWFFWF
FFFFFFFFF
..FF.....
..F......
""",
    # Menu, Bag, PC: a little list.
    'MENU': """
FFFFFFF
FWWWWWF
FFFFFFF
FWWWWWF
FFFFFFF
FWWWWWF
FFFFFFF
""",
    # Battle: crossed swords.
    'BATTLE': """
W.......W
WW.....WW
.WW...WW.
..WW.WW..
...WWW...
..FWWWF..
.FF...FF.
FF.....FF
""",
    # A question is open between the two players.
    'INVITE': """
..FFFFF..
.FFWWWFF.
FFWFFFWFF
FFFFFFWFF
FFFFFWFFF
FFFFWFFFF
FFFFFFFFF
.FFFWFFF.
..FFFFF..
""",
    # Waiting at a shared checkpoint: a tick.
    'WAIT': """
..FFFFF..
.FFFFFFF.
FFFFFFFWF
FFFFFFWWF
FWFFFWWFF
FWWFWWFFF
FFWWWFFFF
.FFWFFFF.
..FFFFF..
""",
    # The link is recovering: a chain with a gap.
    'BROKEN': """
.FFF.....FFF.
F...F...F...F
F...FW.WF...F
F...F...F...F
.FFF.....FFF.
""",
}
ORDER = ['WALK', 'TALK', 'MENU', 'BATTLE', 'INVITE', 'WAIT', 'BROKEN']
COLOUR = {'.': 0, 'W': 12, 'H': 13, 'F': 14}


def outline(grid):
    h, w = len(grid), len(grid[0])
    out = [row[:] for row in grid]
    for y in range(h):
        for x in range(w):
            if grid[y][x]:
                continue
            for dy in (-1, 0, 1):
                for dx in (-1, 0, 1):
                    yy, xx = y + dy, x + dx
                    if 0 <= yy < h and 0 <= xx < w and grid[yy][xx]:
                        out[y][x] = 15
    return out


def place(mask, bottom=True):
    rows = [r for r in mask.strip('\n').split('\n')]
    h, w = len(rows), max(len(r) for r in rows)
    grid = [[0] * 16 for _ in range(16)]
    ox = (16 - w) // 2
    oy = 16 - h - 1 if bottom else (16 - h) // 2
    for y, r in enumerate(rows):
        for x, ch in enumerate(r.ljust(w, '.')):
            grid[oy + y][ox + x] = COLOUR[ch]
    return outline(grid)


def arrow(angle):
    # An arrow pointing along `angle` (0 = east, 90 = north), drawn by
    # sampling a north-pointing shape rotated about the centre.
    shape = """
....F....
...FFF...
..FFFFF..
.FFFFFFF.
FFFFFFFFF
...FFF...
...FFF...
...FFF...
"""
    rows = shape.strip('\n').split('\n')
    h, w = len(rows), len(rows[0])
    grid = [[0] * 16 for _ in range(16)]
    t = math.radians(angle - 90)   # rotation from the north-pointing shape
    ct, st = math.cos(t), math.sin(t)
    for y in range(16):
        for x in range(16):
            mx, my = x - 7.5, 7.5 - y          # maths axes, y up
            sx = mx * ct + my * st             # rotate back by t
            sy = -mx * st + my * ct
            u = sx + (w - 1) / 2
            v = (h - 1) / 2 - sy
            ui, vi = int(math.floor(u + 0.5)), int(math.floor(v + 0.5))
            if 0 <= vi < h and 0 <= ui < w and rows[vi][ui] == 'F':
                grid[y][x] = 14
    # the arrow's tip in white for contrast
    return outline(grid)


def tiles(grid):
    words = []
    for ty in (0, 1):
        for tx in (0, 1):
            for y in range(8):
                v = 0
                for x in range(8):
                    v |= grid[ty * 8 + y][tx * 8 + x] << (4 * x)
                words.append(v)
    return words


def main():
    out = ['// Generated by tools/coop_art/marker_icons.py: the partner marker icons',
           '// and edge arrows, 16x16 4bpp, four tiles each (top-left, top-right,',
           '// bottom-left, bottom-right). Colours 12 white, 13 highlight, 14 fill,',
           '// 15 outline.', '']
    out.append('enum {')
    for name in ORDER:
        out.append('    COOP_ICON_%s,' % name)
    for name in ['ARROW_E', 'ARROW_NE', 'ARROW_N', 'ARROW_NW', 'ARROW_W', 'ARROW_SW', 'ARROW_S', 'ARROW_SE']:
        out.append('    COOP_ICON_%s,' % name)
    out.append('    COOP_ICON_COUNT,')
    out.append('};')
    out.append('')
    out.append('static const u32 sCoopMarkerIconTiles[COOP_ICON_COUNT * 4 * 8] = {')
    grids = [(n, place(ICONS[n])) for n in ORDER]
    ne = """
..FFFFFF
....FFFF
...FFFFF
..FFF.FF
.FFF...F
FFF.....
FF......
"""
    rows = ne.strip('\n').split('\n')
    def flip(rs, h, v):
        rs = [r[::-1] for r in rs] if h else rs
        return rs[::-1] if v else rs
    diag = {45: flip(rows, 0, 0), 135: flip(rows, 1, 0), 225: flip(rows, 1, 1), 315: flip(rows, 0, 1)}
    for a in range(0, 360, 45):
        if a in diag:
            grids.append(('ARROW_%d' % a, place('\n'.join(diag[a]), bottom=False)))
        else:
            grids.append(('ARROW_%d' % a, arrow(a)))
    for name, g in grids:
        out.append('    // %s' % name)
        for row in g:
            out.append('    // ' + ''.join('.wHFO'[[0, 12, 13, 14, 15].index(c)] for c in row))
        ws = tiles(g)
        for i in range(0, len(ws), 8):
            out.append('    ' + ', '.join('0x%08X' % w for w in ws[i:i + 8]) + ',')
    out.append('};')
    print('\n'.join(out))


if __name__ == '__main__':
    main()
