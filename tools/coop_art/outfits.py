#!/usr/bin/env python3
"""Player outfit presets: six colour sets for each player base (Brendan,
May). Only clothing indices change; skin, hair, eyes, outlines and the
transparent colour are kept, so every pose that uses the player palette
(walk, run, bikes, surf, field moves, fishing, watering, decorating) and
the trainer pics (battle back pic, trainer card, intro) stay consistent.

Writes src/data/coop_outfits.h. --preview DIR renders a sheet per base.
Index roles are the same in the overworld and trainer palettes:
  Brendan: 5-8 jacket ramp, a/b accent (band, strap), c/d shirt
  May:     c/d top, a/b accent (bandana, belt), 5/6 shorts
"""
import os, sys
from PIL import Image

ROOT = os.path.abspath(os.path.join(os.path.dirname(__file__), '..', '..'))


def read_pal(path):
    v = [int(x) for x in open(path).read().split()[3:3 + 48]]
    return [tuple(v[i:i + 3]) for i in range(0, 48, 3)]


GROUPS = {
    'brendan': {'main': [5, 6, 7, 8], 'accent': [10, 11], 'shirt': [12, 13]},
    'may': {'main': [12, 13], 'accent': [10, 11], 'shorts': [5, 6]},
}

# name, {group: target colour for the group's lightest member}
PRESETS = {
    'brendan': [
        ('CLASSIC', {}),
        ('FOREST', {'main': (98, 156, 82), 'accent': (238, 172, 57), 'shirt': (246, 238, 205)}),
        ('CHARCOAL', {'main': (123, 123, 131), 'accent': (98, 180, 238), 'shirt': (255, 205, 74)}),
        ('OCEAN', {'main': (65, 164, 180), 'accent': (255, 222, 98), 'shirt': (246, 115, 98)}),
        ('PLUM', {'main': (148, 98, 180), 'accent': (246, 148, 197), 'shirt': (131, 213, 230)}),
        ('SUNSET', {'main': (213, 115, 65), 'accent': (115, 82, 57), 'shirt': (255, 238, 131)}),
    ],
    'may': [
        ('CLASSIC', {}),
        ('SKY', {'main': (98, 172, 246), 'accent': (238, 238, 246), 'shorts': (74, 82, 131)}),
        ('LEMON', {'main': (255, 213, 74), 'accent': (246, 123, 57), 'shorts': (98, 98, 106)}),
        ('LILAC', {'main': (189, 139, 230), 'accent': (255, 222, 123), 'shorts': (82, 65, 98)}),
        ('ROSE', {'main': (255, 148, 189), 'accent': (139, 98, 213), 'shorts': (65, 65, 74)}),
        ('FOREST', {'main': (98, 164, 82), 'accent': (246, 205, 98), 'shorts': (123, 98, 65)}),
    ],
}

KINDS = [
    ('ow', 'graphics/object_events/palettes/%s.pal'),
    ('ow_reflection', 'graphics/object_events/palettes/%s_reflection.pal'),
    ('trainer', 'graphics/trainers/palettes/%s.pal'),
]


def lum(c):
    return 0.30 * c[0] + 0.59 * c[1] + 0.11 * c[2] + 1


def recolour(base, refpal, base_name, preset):
    """refpal: the base's own overworld palette, which sets the ramp shape
    (so a reflection follows the same change as the sprite)."""
    out = list(base)
    for group, target in preset.items():
        idx = GROUPS[base_name][group]
        top = max(idx, key=lambda i: lum(refpal[i]))
        for i in idx:
            k = lum(refpal[i]) / lum(refpal[top])
            new = tuple(min(255, int(t * k)) for t in target)
            if base is refpal:
                out[i] = new
            else:
                # reflection: keep the base's tint over the new colour
                r = tuple(base[i][j] / max(refpal[i][j], 24) for j in range(3))
                out[i] = tuple(min(255, int(new[j] * r[j])) for j in range(3))
    return out


def gba(c):
    return (c[0] >> 3) | ((c[1] >> 3) << 5) | ((c[2] >> 3) << 10)


def build():
    tables = {}
    for name in ('brendan', 'may'):
        ow = read_pal(os.path.join(ROOT, KINDS[0][1] % name))
        for kind, path in KINDS:
            base = read_pal(os.path.join(ROOT, path % name))
            ref = ow if kind != 'trainer' else base
            for p, (pname, preset) in enumerate(PRESETS[name]):
                if kind == 'ow_reflection':
                    tables[(name, kind, p)] = recolour(base, ow, name, preset)
                else:
                    tables[(name, kind, p)] = recolour(base, base, name, preset)
    return tables


def write_header(tables):
    lines = ['// Generated by tools/coop_art/outfits.py; do not edit.',
             '// [base: 0 Brendan, 1 May][kind: overworld, reflection, trainer][preset][16]',
             '#define COOP_OUTFIT_KINDS 3', '',
             'static const u16 sCoopOutfitPals[2][COOP_OUTFIT_KINDS][COOP_OUTFIT_COUNT][16] = {']
    for name in ('brendan', 'may'):
        lines.append('    {')
        for kind, _ in KINDS:
            lines.append('        {')
            for p in range(6):
                vals = ', '.join('0x%04X' % gba(c) for c in tables[(name, kind, p)])
                lines.append('            {%s},' % vals)
            lines.append('        },')
        lines.append('    },')
    lines.append('};')
    lines.append('')
    lines.append('static const u8 *const sCoopOutfitNames[2][COOP_OUTFIT_COUNT] = {')
    for name in ('brendan', 'may'):
        lines.append('    {%s},' % ', '.join('COMPOUND_STRING("%s")' % n for n, _ in PRESETS[name]))
    lines.append('};')
    open(os.path.join(ROOT, 'src/data/coop_outfits.h'), 'w').write('\n'.join(lines) + '\n')


def preview(tables, outdir):
    os.makedirs(outdir, exist_ok=True)
    for name in ('brendan', 'may'):
        walk = Image.open(os.path.join(ROOT, 'graphics/object_events/pics/people/%s/walking.png' % name))
        bike = Image.open(os.path.join(ROOT, 'graphics/object_events/pics/people/%s/acro_bike.png' % name))
        surf = Image.open(os.path.join(ROOT, 'graphics/object_events/pics/people/%s/surfing.png' % name))
        front = Image.open(os.path.join(ROOT, 'graphics/trainers/front_pics/%s.png' % name))
        back = Image.open(os.path.join(ROOT, 'graphics/trainers/back_pics/%s.png' % name))
        W, H = 64 * 3 + 16 * 3 + 32 * 2 + 40, 90
        sheet = Image.new('RGB', (W * 2, H * 2 * 6), (240, 240, 240))
        for p in range(6):
            def pal(im, kind):
                im = im.copy()
                flat = []
                for c in tables[(name, kind, p)]:
                    flat += list(c)
                im.putpalette(flat + [0] * (768 - len(flat)))
                rgba = im.convert('RGBA')
                px = rgba.load()
                t = tables[(name, kind, p)][0]
                for y in range(rgba.height):
                    for x in range(rgba.width):
                        if im.getpixel((x, y)) == 0:
                            px[x, y] = (0, 0, 0, 0)
                return rgba
            row = Image.new('RGBA', (W, H), (232, 240, 232, 255))
            row.alpha_composite(pal(front, 'trainer'), (0, 4))
            row.alpha_composite(pal(back.crop((0, 0, 64, 64)), 'trainer'), (64, 4))
            w = pal(walk, 'ow')
            for i, f in enumerate((0, 1, 2)):
                row.alpha_composite(w.crop((f * 16, 0, f * 16 + 16, 32)), (132 + i * 18, 20))
            row.alpha_composite(pal(bike, 'ow').crop((0, 0, 32, 32)), (190, 20))
            row.alpha_composite(pal(surf, 'ow').crop((0, 0, 32, 32)), (224, 20))
            sheet.paste(row.convert('RGB').resize((W * 2, H * 2), Image.NEAREST), (0, p * H * 2))
        sheet.save(os.path.join(outdir, 'outfits_%s.png' % name))


if __name__ == '__main__':
    t = build()
    write_header(t)
    if len(sys.argv) > 2 and sys.argv[1] == '--preview':
        preview(t, sys.argv[2])
