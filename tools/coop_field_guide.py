def strblock(label, text):
    lines = text.split('\n')
    out = [label + ':']
    for k, ln in enumerate(lines):
        out.append('\t.string "%s%s"' % (ln, '$' if k == len(lines) - 1 else '\\n'))
    return '\n'.join(out)


