#!/usr/bin/env python3
"""Where to get each evolution item, for the summary screen's evolution hint
(src/coop_evo_hint.c).

    python3 tools/coop_roster_audit/evo_item_hints.py > src/data/coop_evo_item_hints.h

Uses roster.py's sources (shops, gifts, item balls, hidden items, the fossil
maniac), read from the map scripts and map data. Every item an evolution
uses (EVO_ITEM, IF_HOLD_ITEM, IF_BAG_ITEM_COUNT) gets one short line: a
shop that sells it if there is one (quest shops last), else a daily gift,
a person who gives it, or where one lies. Items with no source get none
(the hint then says only what is needed).
"""
import contextlib
import io
import os
import re
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.dirname(os.path.dirname(HERE))
os.chdir(ROOT)
sys.argv = [os.path.join(HERE, 'roster.py')]
sys.path.insert(0, HERE)
g = {'__name__': 'roster', '__file__': os.path.join(HERE, 'roster.py')}
_exit = sys.exit
sys.exit = lambda *a: None
with contextlib.redirect_stdout(io.StringIO()):
    exec(compile(open(os.path.join(HERE, 'roster.py')).read(), 'roster.py', 'exec'), g)
sys.exit = _exit

QUESTS = {'coop_quest_caravan.inc': 'Desert Caravan', 'coop_quest_shoal.inc': 'Shoal quest',
          'coop_quest_coast.inc': 'Coastal Cleanup', 'coop_quest_twins.inc': 'Twin Trial',
          'coop_quest_beacon.inc': 'Beacon quest', 'coop_quest_power.inc': 'Power quest'}
MAX = 26


def place(where):
    if where in QUESTS:
        return QUESTS[where]
    if where == 'MauvilleCity':
        return 'Mauville POWER SHOP'
    if where.endswith('.inc'):
        return None
    w = where
    w = w.replace('DepartmentStore', 'Dept.').replace('PokemonCenter_1F', 'Pokemon Center')
    w = w.replace('FossilManiacsTunnel', 'tunnel').replace('_Mart', ' Mart')
    w = re.sub(r'(City|Town)(?=_|$| )', '', w)
    w = re.sub(r'Route(\d+)', r'Route \1', w)
    w = w.replace('_', ' ')
    w = re.sub(r'(?<=[a-z])(?=[A-Z])', ' ', w)
    w = re.sub(r'\s+', ' ', w).strip()
    return w.replace('Pokemon', 'POKéMON')


RANK = {'shop': 0, 'daily gift': 1, 'given': 2, 'item ball': 3, 'hidden item': 4}
VERB = {'shop': 'Sold', 'daily gift': 'Daily gift', 'given': 'Given', 'item ball': 'Found', 'hidden item': 'Hidden'}


def best_line(item_const):
    srcs = g['item_sources'](item_const)
    cands = []
    for kind, where, renew in srcs:
        p = place(where)
        if not p:
            continue
        quest = g['quest_gated'](where)
        cands.append((RANK.get(kind, 9) + (5 if quest else 0), len(p), kind, p))
    if not cands:
        return None
    cands.sort()
    _, _, kind, p = cands[0]
    line = '%s: %s' % (VERB[kind], p)
    if len(line) > MAX:
        line = line[:MAX - 1].rstrip() + '.'
    return line


def main():
    items = set()
    for sid, lst in g['evos_from'].items():
        for m, p, t, conds in lst:
            if m == 'EVO_ITEM':
                items.add(p)
            for c, a in conds:
                if c in ('IF_HOLD_ITEM', 'IF_BAG_ITEM_COUNT'):
                    items.add(a)
    rows = []
    for it in sorted(items, key=lambda x: int(x) if str(x).isdigit() else 0):
        const = g['ITEM_NAME'].get(int(it)) if str(it).isdigit() else it
        if not const or const == 'ITEM_NONE':
            continue
        line = best_line(const)
        if line:
            rows.append((const, line))
    out = ['// Generated by tools/coop_roster_audit/evo_item_hints.py: where each',
           '// evolution item can be had in this build (summary-screen evolution',
           '// hint). Regenerate after changing shops, gifts or item placements.', '',
           'static const struct { u16 item; const u8 *where; } sEvoItemHints[] = {']
    for const, line in rows:
        out.append('    { %s, COMPOUND_STRING("%s") },' % (const, line.replace('"', "'")))
    out.append('};')
    print('\n'.join(out))


if __name__ == '__main__':
    main()
