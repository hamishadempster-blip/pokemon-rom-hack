#!/usr/bin/env python3
"""Readable manifest for one roster batch, from docs/coop_roster_manifest.json
(written by roster.py, which must run first).

    tools/coop_roster_audit/batch_doc.py BATCH2 > docs/COOP_ROSTER_BATCH2.md
"""
import json, os, sys

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.abspath(os.path.join(HERE, '..', '..'))
sys.path.insert(0, os.path.join(ROOT, 'tools/coop_roster'))
import audit as SRC  # noqa: E402

TITLE = {'BATCH2': 'Second roster batch (build 0xC0170138)'}


def nice(c):
    return (c or '').replace('SPECIES_', '').replace('_', ' ').title()


def where(s):
    m = s['method']
    if m == 'wild':
        return 'Wild, %s: %s, Lv %s, %s%% of the table' % (s['encounter'], s['location'], s['levels'], s['rate_percent'])
    if m.startswith('partner'):
        return 'Partner Pokémon (one a day): %s, Lv %s' % (s['location'], s['levels'])
    if m == 'fossil revival':
        return 'Fossil (%s): %s, Lv %s' % (nice(s['item'].replace('ITEM_', '')), s['location'], s['levels'])
    if m == 'breeding':
        return 'Egg: %s' % s['location']
    return '%s: %s' % (m[0].upper() + m[1:], s['location'])


def main():
    batch = sys.argv[1] if len(sys.argv) > 1 else 'BATCH2'
    names = getattr(SRC, batch)
    man = json.load(open(os.path.join(ROOT, 'docs/coop_roster_manifest.json')))
    by = {}
    for e in man['species']:
        by[e['species'][len('SPECIES_'):]] = e
        by.setdefault(''.join(ch for ch in e['name'].upper() if ch.isalnum()), e)   # forms: ALCREMIE
    out = []
    out.append('# %s: acquisition manifest\n' % TITLE.get(batch, batch))
    out.append('Generated by `tools/coop_roster_audit/batch_doc.py %s` from `docs/coop_roster_manifest.json` '
               '(the whole-roster manifest, written by `tools/coop_roster_audit/roster.py` from the built ROM and the sources). '
               'Rates are the share of that encounter table (grass/cave slots 20/20/10/10/10/10/5/5/4/4/1/1; surf 60/30/5/4/1; '
               'rods by slot). "Verified" names the gameplay scenario that caught, received or evolved it; "source" means '
               'checked from the ROM and sources only.\n' % batch)
    got = [n for n in names if n in by]
    out.append('**%d of %d obtainable** (all solo: %s). Direct sources: %d; by evolution only: %d.\n' % (
        len(got), len(names), 'yes' if all(by[n]['solo'] for n in got) else 'no',
        sum(1 for n in got if any(s['method'] != 'breeding' for s in by[n]['sources'])),
        sum(1 for n in got if not any(s['method'] != 'breeding' for s in by[n]['sources']))))
    out.append('| Pokémon | National / Hoenn No | How to get it | Unlock | Evolution and resources | Renewable | Verified |')
    out.append('|---|---|---|---|---|---|---|')
    for n in names:
        e = by.get(n)
        if not e:
            out.append('| %s | | **not obtainable** | | | | |' % nice(n))
            continue
        srcs = [s for s in e['sources'] if s['method'] != 'breeding']
        how = '<br>'.join(where(s) for s in srcs) or '—'
        unlock = '<br>'.join(sorted({s['requires'] for s in srcs})) or '—'
        evo = []
        evs = e['evolution']
        if len(evs) > 4:   # Alcremie: one entry per sweet, spin and time of day
            extra = len(evs) - 1
            evs = evs[:1]
        else:
            extra = 0
        for v in evs:
            r = '; '.join('%s (%s)' % (nice(x['item'].replace('ITEM_', '')), ', '.join(x['sources'][:3])) for x in v['resources'])
            evo.append('from %s: %s%s' % (nice(v['from']), v['how'], ' — ' + r if r else ''))
        if extra:
            evo.append('and %d more combinations of sweet, spin and time of day (each picks a form)' % extra)
        ver = e.get('verification', 'source')
        if ver.startswith('gameplay: '):
            ver = ver[len('gameplay: '):]
        out.append('| %s | %d / %s | %s | %s | %s | %s | %s |' % (
            e['name'], e['national_dex'], e['hoenn_dex'], how, unlock, '<br>'.join(evo) or '—',
            'yes' if e['renewable'] else 'no', ver))
    print('\n'.join(out))


if __name__ == '__main__':
    main()
